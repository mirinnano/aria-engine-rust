function selectGlBlend(gl, blend) {
  if (blend === "add") gl.blendFunc(gl.SRC_ALPHA, gl.ONE);
  else if (blend === "multiply") gl.blendFunc(gl.DST_COLOR, gl.ZERO);
  else gl.blendFunc(gl.SRC_ALPHA, gl.ONE_MINUS_SRC_ALPHA);
}

function createGlProgram(gl, vertex, fragment) {
  const compile = (type, source) => {
    const shader = gl.createShader(type);
    gl.shaderSource(shader, source);
    gl.compileShader(shader);
    if (!gl.getShaderParameter(shader, gl.COMPILE_STATUS)) {
      const error = gl.getShaderInfoLog(shader);
      gl.deleteShader(shader);
      throw new Error(`WebGL shader compilation failed: ${error}`);
    }
    return shader;
  };
  const program = gl.createProgram();
  gl.attachShader(program, compile(gl.VERTEX_SHADER, vertex));
  gl.attachShader(program, compile(gl.FRAGMENT_SHADER, fragment));
  gl.linkProgram(program);
  if (!gl.getProgramParameter(program, gl.LINK_STATUS)) {
    const error = gl.getProgramInfoLog(program);
    gl.deleteProgram(program);
    throw new Error(`WebGL program link failed: ${error}`);
  }
  return program;
}

function createGpuPipeline(device, format, blend) {
  return device.createRenderPipeline({
    layout: "auto",
    vertex: {
      module: device.createShaderModule({ code: WEBGPU_SHADER }),
      entryPoint: "vs_main",
      buffers: [{
        arrayStride: 52,
        attributes: [
          { shaderLocation: 0, offset: 0, format: "float32x2" },
          { shaderLocation: 1, offset: 8, format: "float32x2" },
          { shaderLocation: 2, offset: 16, format: "float32x4" },
          { shaderLocation: 3, offset: 32, format: "float32x4" },
          { shaderLocation: 4, offset: 48, format: "float32" },
        ],
      }],
    },
    fragment: {
      module: device.createShaderModule({ code: WEBGPU_SHADER }),
      entryPoint: "fs_main",
      targets: [{ format, blend }],
    },
    primitive: { topology: "triangle-list" },
  });
}

