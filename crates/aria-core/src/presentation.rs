//! Typed, layout-free contract between the deterministic VM and a game UI.
//!
//! The core owns narrative state and validates semantic intents. A host owns
//! DOM layout, hit testing, focus, styling, and accessibility. Keeping those
//! responsibilities apart prevents a second UI DSL from growing inside the
//! bytecode format.

use std::collections::BTreeMap;

use serde::{Deserialize, Serialize};

use crate::vm::{AutoMode, SettingsState, SkipMode};

/// Version of the JSON view contract consumed by game presentation packages.
/// Schema 10 adds the total of an authored hold and the plugin that owns
/// the current screen.
pub const UI_VIEW_MODEL_SCHEMA: u16 = 10;

/// Standard surfaces understood by the engine. A frontend may render a
/// project-specific surface for [`Self::Custom`] without changing the VM
/// layout protocol.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", content = "name", rename_all = "snake_case")]
pub enum UiRoute {
    Setup,
    Title,
    /// A self-contained endpoint for a content-limited public build. It is
    /// a base route rather than an overlay, so restoring a save preserves
    /// the fact that the trial has ended.
    DemoEnd,
    Dialogue,
    Pause,
    Save,
    Load,
    Settings,
    Backlog,
    ChapterSelect,
    Gallery,
    Confirm,
    Custom(String),
}

impl UiRoute {
    #[must_use]
    pub fn parse(value: &str) -> Self {
        match value {
            "setup" => Self::Setup,
            "title" => Self::Title,
            "demo_end" => Self::DemoEnd,
            "dialogue" => Self::Dialogue,
            "pause" => Self::Pause,
            "save" => Self::Save,
            "load" => Self::Load,
            "settings" => Self::Settings,
            "backlog" => Self::Backlog,
            "chapter_select" => Self::ChapterSelect,
            "gallery" => Self::Gallery,
            "confirm" => Self::Confirm,
            other => Self::Custom(other.to_owned()),
        }
    }

    #[must_use]
    pub fn as_str(&self) -> &str {
        match self {
            Self::Setup => "setup",
            Self::Title => "title",
            Self::DemoEnd => "demo_end",
            Self::Dialogue => "dialogue",
            Self::Pause => "pause",
            Self::Save => "save",
            Self::Load => "load",
            Self::Settings => "settings",
            Self::Backlog => "backlog",
            Self::ChapterSelect => "chapter_select",
            Self::Gallery => "gallery",
            Self::Confirm => "confirm",
            Self::Custom(value) => value,
        }
    }

    #[must_use]
    pub const fn is_overlay(&self) -> bool {
        matches!(
            self,
            Self::Pause
                | Self::Save
                | Self::Load
                | Self::Settings
                | Self::Backlog
                | Self::ChapterSelect
                | Self::Gallery
                | Self::Confirm
        )
    }
}

/// A semantic input generated by a presentation package. It carries no pixel
/// coordinates, DOM selector, or visual style.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum UiIntent {
    Activate { id: String },
    OpenRoute { route: String },
    Dismiss,
    SetSetting { name: String, value: f32 },
    ToggleSetting { name: String },
    Scroll { region: String, delta_y: f32 },
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CameraView {
    pub zoom: u32,
    pub pan_x: i64,
    pub pan_y: i64,
    pub duration_ms: u32,
    pub easing: String,
}

/// Stable game identity and locale consumed by the presentation package.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct GameView {
    pub id: String,
    pub locale: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct DialogueView {
    pub speaker: Option<String>,
    /// Declared character id (`character mio { … }`), for per-speaker styling.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub speaker_id: Option<String>,
    /// Ruby and emphasis over `full_page_text`, as page-relative grapheme ranges.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub markup: Vec<crate::markup::MarkupSpan>,
    /// The complete authored line. It remains available for transcript tools,
    /// while the reading surface should use `full_page_text` and `text`.
    pub full_text: String,
    /// The complete current subtitle page, including deterministic explicit
    /// line breaks. `text` is its currently revealed prefix.
    pub full_page_text: String,
    /// One-based page position within `full_text`.
    pub page_number: u32,
    pub page_count: u32,
    /// Stable identifier used by history/replay. It carries no DOM identity.
    pub page_id: String,
    /// Width of the deterministic subtitle grid in display cells.
    pub columns: u16,
    pub text: String,
    pub complete: bool,
    pub awaiting_advance: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ChoiceView {
    pub id: String,
    pub label: String,
    pub selected: bool,
    /// A `chapter id;` option names its chapter; its metadata is in `chapters`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub chapter: Option<String>,
}

/// An action supplied by the engine. Its display label belongs to the game
/// frontend's locale catalog, not to a renderer baked into ARIAC.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ActionView {
    pub id: String,
    pub enabled: bool,
    #[serde(default)]
    pub active: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BacklogEntryView {
    pub id: String,
    /// Stable page target accepted by the resume confirmation flow.
    pub resume_id: String,
    pub speaker: Option<String>,
    pub text: String,
    pub locale: String,
    pub timestamp_ms: u64,
    pub selected: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ChapterView {
    pub id: String,
    pub title: String,
    pub description: String,
    pub thumbnail: Option<String>,
    pub script: Option<String>,
    pub unlocked: bool,
    pub progress: u8,
    /// Declared catalogue fields (`label "DAY 1"`, `numeral "I"`, `date`).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub label: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub numeral: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub date: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct GalleryItemView {
    pub id: String,
    pub unlocked: bool,
    pub selected: bool,
    /// From the script's `cg id { title …; image …; }` declaration.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub title: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub image: Option<String>,
}

/// One `item` of a script `collection`: its id and string fields.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CollectionItemView {
    pub id: String,
    pub fields: BTreeMap<String, String>,
}

/// Validated plugin policy for the active custom surface. Hosts can route
/// input without knowing a particular game's screen names. Visual curves and
/// components remain presentation-owned.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct StorySurfaceView {
    pub first_visit: bool,
    pub reading_surface: bool,
    pub atomic_text: bool,
    pub advance_action: Option<String>,
}

/// A destructive presentation action that must be explicitly acknowledged.
/// The frontend owns the words and visual treatment; the VM owns which
/// action is pending so a confirmation cannot be forged or lost on save.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ConfirmationView {
    pub action: String,
    pub resume_id: Option<String>,
}

/// The complete non-visual state for one React/UI update.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct UiViewModel {
    pub schema_version: u16,
    pub route: UiRoute,
    pub route_stack: Vec<UiRoute>,
    pub game: GameView,
    /// The semantic cue authored for the current backdrop (`stage ward;`).
    /// It resets on every `background`; the presentation owns its look.
    #[serde(default)]
    pub stage: Option<String>,
    /// Target framing of the backdrop; the presentation eases toward it over
    /// `duration_ms`. Absent means the unmoved full frame.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub camera: Option<CameraView>,
    pub dialogue: Option<DialogueView>,
    /// A story-authored timer currently owns the VM. `None` means the host
    /// may sleep until input, resize, or a distinct active visual transition.
    #[serde(default)]
    pub timed_hold_remaining_ms: Option<u32>,
    /// The whole length of the current authored hold, so a presentation can
    /// draw its progress without assuming a duration.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub timed_hold_total_ms: Option<u32>,
    /// The plugin that registered the current screen. A Web presentation
    /// can mount that plugin's UI module for it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub route_plugin: Option<String>,
    /// The script's `collection` declarations, by name. What the story says
    /// lives here; how it is laid out stays with the presentation.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    pub collections: BTreeMap<String, Vec<CollectionItemView>>,
    pub choices: Vec<ChoiceView>,
    pub actions: Vec<ActionView>,
    pub settings: SettingsState,
    /// Only a virtual window is populated while the backlog route is open.
    /// A normal reading update therefore never clones or serializes the full
    /// history merely because another grapheme appeared.
    pub backlog: Vec<BacklogEntryView>,
    pub backlog_total: u32,
    pub backlog_start: u32,
    pub chapters: Vec<ChapterView>,
    pub gallery: Vec<GalleryItemView>,
    pub gallery_viewer: Option<String>,
    pub story_surface: Option<StorySurfaceView>,
    pub confirmation: Option<ConfirmationView>,
    pub scroll_offsets: BTreeMap<String, f32>,
    pub auto_mode: AutoMode,
    pub skip_mode: SkipMode,
    pub reduced_motion: bool,
}
